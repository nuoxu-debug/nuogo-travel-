export function translate(language, key) {
  const parts = key.split(".");
  return parts.reduce(
    (value, part) => value?.[part],
    collaborationTranslations[language]
  ) ?? parts.reduce(
    (value, part) => value?.[part],
    translations[language]
  ) ?? key;
}
